const certificateDescription = "A TLS certificate for the VergeOS UI and API. type is manual, letsencrypt, or self_signed. Changing type replaces the certificate. Changing a configured domain_name replaces it too. Omitting domain_name leaves the current name in place. A manual certificate requires public_certificate and private_key_wo. private_key_wo is sent when the certificate is created and when private_key_wo_version changes. Terraform stores the version, not the private key. An ACME certificate (letsencrypt) requires domain_list or domain_name, a contact user id, and agree_tos set to true. eab_hmac_key_wo is the external account binding secret for a private ACME server. Terraform stores eab_hmac_key_wo_version, not that secret. A self_signed certificate is generated by VergeOS from domain_name."

