func (r *certificateResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan, config certificateModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.api.createCertificate(ctx, &plan, secret(config.PrivateKeyWO), secret(config.EABHMACKeyWO)); err != nil {
		resp.Diagnostics.AddError("Error creating certificate", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, certificateForState(&plan))...)
	shared.RememberIdentity(ctx, &resp.Diagnostics, resp.Identity, plan.ID)
}

func (r *certificateResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data certificateModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.api.readCertificate(ctx, &data); err != nil {
		if vergeos.IsNotFoundError(err) {
			shared.RememberIdentity(ctx, &resp.Diagnostics, resp.Identity, data.ID)
			if resp.Diagnostics.HasError() {
				return
			}
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Error reading certificate", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, certificateForState(&data))...)
	shared.RememberIdentity(ctx, &resp.Diagnostics, resp.Identity, data.ID)
}

func (r *certificateResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state, config certificateModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}
	privateKey := ""
	if versionChanged(plan.PrivateKeyWOVersion, state.PrivateKeyWOVersion) {
		privateKey = secret(config.PrivateKeyWO)
	}
	hmac := ""
	if versionChanged(plan.EABHMACKeyWOVersion, state.EABHMACKeyWOVersion) {
		hmac = secret(config.EABHMACKeyWO)
	}
	if err := r.api.updateCertificate(ctx, &plan, &state, privateKey, hmac); err != nil {
		resp.Diagnostics.AddError("Error updating certificate", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, certificateForState(&plan))...)
	shared.RememberIdentity(ctx, &resp.Diagnostics, resp.Identity, plan.ID)
}

func (r *certificateResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var data certificateModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}
	id, err := parseID(data.ID, "certificate")
	if err != nil {
		resp.Diagnostics.AddError("Error deleting certificate", err.Error())
		return
	}
	if err := r.api.deleteCertificate(ctx, id); err != nil {
		resp.Diagnostics.AddError("Error deleting certificate", err.Error())
		return
	}
	tflog.Debug(ctx, fmt.Sprintf("deleted certificate %d", id))
}

