func validateCertificate(data certificateModel, privateKey string, requirePrivate bool) error {
	if !knownString(data.Type) {
		return nil
	}
	switch data.Type.ValueString() {
	case vergeos.CertificateTypeManual:
		if !knownString(data.PublicCertificate) || data.PublicCertificate.ValueString() == "" {
			return fmt.Errorf("type manual requires public_certificate")
		}
		if requirePrivate && privateKey == "" {
			return fmt.Errorf("type manual requires private_key_wo and private_key_wo_version")
		}
	case vergeos.CertificateTypeSelfSigned:
		if !knownString(data.DomainName) || data.DomainName.ValueString() == "" {
			return fmt.Errorf("type self_signed requires domain_name")
		}
	case vergeos.CertificateTypeLetsEncrypt:
		hasDomain := (knownString(data.DomainName) && data.DomainName.ValueString() != "") ||
			(knownString(data.DomainList) && data.DomainList.ValueString() != "")
		if !hasDomain {
			return fmt.Errorf("type letsencrypt requires domain_name or domain_list")
		}
		if !knownInt(data.Contact) {
			return fmt.Errorf("type letsencrypt requires contact, the user id for the ACME account email")
		}
		if !knownBool(data.AgreeTOS) || !data.AgreeTOS.ValueBool() {
			return fmt.Errorf("type letsencrypt requires agree_tos = true")
		}
	default:
		return fmt.Errorf("type must be manual, letsencrypt, or self_signed")
	}
	return nil
}

func (a *API) createCertificate(ctx context.Context, data *certificateModel, privateKey, hmac string) error {
	if err := a.requireSDK(); err != nil {
		return err
	}
	if err := validateCertificate(*data, privateKey, true); err != nil {
		return err
	}
	contact, err := knownIntPtr(data.Contact)
	if err != nil {
		return err
	}
	req := &vergeos.CertificateCreateRequest{
		DomainName:  stringValue(data.DomainName),
		DomainList:  stringValue(data.DomainList),
		Description: stringValue(data.Description),
		Type:        data.Type.ValueString(),
		Public:      stringValue(data.PublicCertificate),
		Private:     privateKey,
		Chain:       stringValue(data.Chain),
		ACMEServer:  stringValue(data.ACMEServer),
		EABKid:      stringValue(data.EABKid),
		EABHMACKey:  hmac,
		KeyType:     stringValue(data.KeyType),
		RSAKeySize:  stringValue(data.RSAKeySize),
		Contact:     contact,
		AgreeTOS:    boolPtr(data.AgreeTOS),
	}
	id, err := a.createCertificateRow(ctx, req)
	if err != nil {
		return err
	}
	got, err := a.sdk.Certificates.Get(ctx, id)
	if err != nil {
		return err
	}
	return a.applyCertificate(ctx, data, certificateWithID(got, id), *data)
}

// createCertificateRow posts the certificate and returns the new key.
// The key comes from the create response, so a later Get that omits $key
// cannot drop the id after VergeOS has already stored the row.
func (a *API) createCertificateRow(ctx context.Context, req *vergeos.CertificateCreateRequest) (int, error) {
	if a == nil || a.http == nil {
		return 0, fmt.Errorf("vergeio client is nil")
	}
	buf, err := json.Marshal(req)
	if err != nil {
		return 0, err
	}
	resp, err := a.http.Post(ctx, certificateCollection, bytes.NewBuffer(buf))
	if err != nil {
		return 0, err
	}
	if resp == nil || resp.Body == nil {
		return 0, fmt.Errorf("empty response from certificate create")
	}
	defer func() { _ = resp.Body.Close() }()
	var created struct {
		Key vergeos.FlexInt `json:"$key"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&created); err != nil {
		return 0, fmt.Errorf("decode certificate create: %w", err)
	}
	if created.Key <= 0 {
		return 0, fmt.Errorf("certificate create did not return a key")
	}
	return int(created.Key), nil
}

func (a *API) readCertificate(ctx context.Context, data *certificateModel) error {
	if err := a.requireSDK(); err != nil {
		return err
	}
	id, err := parseID(data.ID, "certificate")
	if err != nil {
		return err
	}
	got, err := a.sdk.Certificates.Get(ctx, id)
	if err != nil {
		return err
	}
	if got != nil && int(got.Key) != id {
		tflog.Debug(ctx, fmt.Sprintf("certificate read requested id %d and VergeOS returned key %d", id, int(got.Key)))
	}
	return a.applyCertificate(ctx, data, certificateWithID(got, id), *data)
}

func (a *API) updateCertificate(ctx context.Context, plan, state *certificateModel, privateKey, hmac string) error {
	if err := a.requireSDK(); err != nil {
		return err
	}
	if err := validateCertificate(*plan, privateKey, false); err != nil {
		return err
	}
	id, err := parseID(state.ID, "certificate")
	if err != nil {
		return err
	}
	contact, err := changedIntPtr(plan.Contact, state.Contact)
	if err != nil {
		return err
	}
	req := &vergeos.CertificateUpdateRequest{
		DomainList:  changedString(plan.DomainList, state.DomainList),
		Description: changedString(plan.Description, state.Description),
		Public:      changedString(plan.PublicCertificate, state.PublicCertificate),
		Chain:       changedString(plan.Chain, state.Chain),
		ACMEServer:  changedString(plan.ACMEServer, state.ACMEServer),
		EABKid:      changedString(plan.EABKid, state.EABKid),
		KeyType:     changedString(plan.KeyType, state.KeyType),
		RSAKeySize:  changedString(plan.RSAKeySize, state.RSAKeySize),
		Contact:     contact,
		AgreeTOS:    changedBool(plan.AgreeTOS, state.AgreeTOS),
	}
	if privateKey != "" {
		req.Private = &privateKey
	}
	if hmac != "" {
		req.EABHMACKey = &hmac
	}
	if !certificateUpdateEmpty(req) {
		if _, err := a.sdk.Certificates.Update(ctx, id, req); err != nil {
			return err
		}
	}
	plan.ID = state.ID
	got, err := a.sdk.Certificates.Get(ctx, id)
	if err != nil {
		return err
	}
	return a.applyCertificate(ctx, plan, certificateWithID(got, id), *plan)
}

func (a *API) deleteCertificate(ctx context.Context, id int) error {
	if err := a.requireSDK(); err != nil {
		return err
	}
	return ignoreMissing(a.sdk.Certificates.Delete(ctx, id))
}

func (a *API) applyCertificate(ctx context.Context, data *certificateModel, cert *vergeos.Certificate, prior certificateModel) error {
	if cert == nil {
		return fmt.Errorf("certificate response was empty")
	}
	id := int(cert.Key)
	row, err := a.readCertificateDetail(ctx, id)
	if err != nil {
		return err
	}
	publicRaw := strings.TrimSpace(row.Public)
	public := certificatePublic(publicRaw)
	pemName := domainFromPEM(public)
	domain := firstNonEmpty(row.Domain, cert.Domain)
	domainList := firstNonEmpty(row.DomainList, cert.DomainList)
	chosen := chooseCertificateDomainName(cert.Type, domain, row.DomainName, domainList, public)
	tflog.Debug(ctx, fmt.Sprintf(
		"certificate read id=%d type=%s domain=%q domainname=%q public=%q pem=%q chosen=%q",
		id, cert.Type, domain, row.DomainName, summarizeCertificatePublic(publicRaw), pemName, chosen,
	))
	data.ID = idString(id)
	if cert.Type != "" {
		data.Type = types.StringValue(cert.Type)
	} else if knownString(prior.Type) {
		data.Type = prior.Type
	}
	data.Domain = stringFromAPI(domain, prior.Domain)
	data.DomainName = applyDomainName(prior.DomainName, chosen)
	data.DomainList = stringFromAPI(domainList, prior.DomainList)
	data.Description = stringFromAPI(cert.Description, prior.Description)
	data.PublicCertificate = keepPEM(public, prior.PublicCertificate)
	data.Chain = keepPEM(row.Chain, prior.Chain)
	data.ACMEServer = stringFromAPI(cert.ACMEServer, prior.ACMEServer)
	data.EABKid = keepConfiguredString(cert.EABKid, prior.EABKid)
	data.KeyType = stringFromAPI(cert.KeyType, prior.KeyType)
	data.RSAKeySize = stringFromAPI(cert.RSAKeySize, prior.RSAKeySize)
	data.Contact = intFromAPI(int(cert.Contact), prior.Contact)
	data.AgreeTOS = boolFromAPI(cert.AgreeTOS, prior.AgreeTOS)
	data.Valid = types.BoolValue(cert.Valid)
	data.AutoCreated = types.BoolValue(cert.AutoCreated)
	data.Expires = timestampFromAPI(cert.Expires)
	data.Created = timestampFromAPI(cert.Created)
	data.Modified = timestampFromAPI(cert.Modified)
	data.PrivateKeyWOVersion = prior.PrivateKeyWOVersion
	data.EABHMACKeyWOVersion = prior.EABHMACKeyWOVersion
	return nil
}

// certificateDetailFields is one read of the certificate row.
// Certificates.Get does not ask for domainname, and a public value of
// "self" is not a PEM. domainname is the name stored at create.
const certificateDetailFields = "domain,domainname,domainlist,public,chain"

type certificateDetail struct {
	Domain     string `json:"domain"`
	DomainName string `json:"domainname"`
	DomainList string `json:"domainlist"`
	Public     string `json:"public"`
	Chain      string `json:"chain"`
}

func (a *API) readCertificateDetail(ctx context.Context, id int) (certificateDetail, error) {
	var row certificateDetail
	if a == nil || a.http == nil {
		return row, fmt.Errorf("vergeio client is nil")
	}
	if id <= 0 {
		return row, fmt.Errorf("certificate id is empty")
	}
	err := a.getJSON(ctx, vergeio.ObjectPath(certificateCollection, strconv.Itoa(id)), &vergeio.Options{Fields: certificateDetailFields}, &row)
	return row, err
}

// certificatePublic drops the sentinel VergeOS uses when a generated
// certificate has no PEM yet. Parsing that text is not a domain lookup.
func certificatePublic(raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" || strings.EqualFold(raw, "self") {
		return ""
	}
	return raw
}

func summarizeCertificatePublic(raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return ""
	}
	if strings.Contains(raw, "BEGIN CERTIFICATE") {
		return "pem"
	}
	return raw
}

func certificateWithID(cert *vergeos.Certificate, id int) *vergeos.Certificate {
	if cert == nil {
		if id <= 0 {
			return nil
		}
		cert = &vergeos.Certificate{}
	}
	if int(cert.Key) <= 0 && id > 0 {
		cert.Key = vergeos.FlexInt(id)
	}
	return cert
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if name := strings.TrimSpace(value); name != "" {
			return name
		}
	}
	return ""
}

// applyDomainName keeps a domain_name already in state. Import starts
// with only the certificate key, so chosen is the name from this read.
func applyDomainName(prior types.String, chosen string) types.String {
	if knownString(prior) {
		return prior
	}
	if strings.TrimSpace(chosen) == "" {
		return types.StringNull()
	}
	return types.StringValue(strings.TrimSpace(chosen))
}

// chooseCertificateDomainName picks the import name.
// A manual certificate keeps domain when VergeOS reports one.
// Any other type uses domainname when that field is present, and does
// not use the certificate subject in that case.
func chooseCertificateDomainName(certType, domain, storedName, domainList, publicPEM string) string {
	domain = strings.TrimSpace(domain)
	storedName = strings.TrimSpace(storedName)
	if certType == vergeos.CertificateTypeManual && domain != "" {
		return domain
	}
	if storedName != "" {
		return storedName
	}
	if domain != "" {
		return domain
	}
	if name := firstDomain(domainList); name != "" {
		return name
	}
	return domainFromPEM(certificatePublic(publicPEM))
}

func firstDomain(list string) string {
	for _, part := range strings.Split(list, ",") {
		part = strings.TrimSpace(part)
		if part != "" {
			return part
		}
	}
	return ""
}

func domainFromPEM(pemText string) string {
	rest := []byte(pemText)
	for {
		var block *pem.Block
		block, rest = pem.Decode(rest)
		if block == nil {
			return ""
		}
		if block.Type != "CERTIFICATE" {
			continue
		}
		parsed, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			continue
		}
		if cn := strings.TrimSpace(parsed.Subject.CommonName); cn != "" {
			return cn
		}
		for _, name := range parsed.DNSNames {
			name = strings.TrimSpace(name)
			if name != "" {
				return name
			}
		}
	}
}

func boolPtr(v types.Bool) *bool {
	if !knownBool(v) {
		return nil
	}
	b := v.ValueBool()
	return &b
}

func certificateUpdateEmpty(req *vergeos.CertificateUpdateRequest) bool {
	if req == nil {
		return true
	}
	return req.DomainList == nil &&
		req.Description == nil &&
		req.Public == nil &&
		req.Private == nil &&
		req.Chain == nil &&
		req.ACMEServer == nil &&
		req.EABKid == nil &&
		req.EABHMACKey == nil &&
		req.KeyType == nil &&
		req.RSAKeySize == nil &&
		req.Contact == nil &&
		req.AgreeTOS == nil &&
		req.Renew == nil
}
